#include <stdio.h>

int main() {
    int p;
    scanf_s("%d", &p);

    // (p % 4 == 0) е 1, ако се дели на 4
    // (p % 7 == 0) е 1, ако се дели на 7
    int result = (p % 4 == 0) || (p % 7 == 0); //Логическо или ни дава истина,
                                             // ако един от изразите се изчистли до истина

    printf("%d\n", result);
    return 0;
}